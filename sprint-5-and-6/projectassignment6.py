genre_artist_df = df.select("genre", "artist_name", "track_name", "popularity",
  "tempo", "danceability", "duration_ms")
key_df = df.select("track_name", "key", "mode", "popularity", "loudness",
  "energy")

genre_statistics = genre_artist_df.groupBy("genre", "artist_name") \
  .agg(F.count("track_name").alias("number_of_tracks"),
       F.round(F.avg("popularity"), 3).alias("avg_popularity"),
       F.round(F.avg("tempo"), 3).alias("avg_bpm")) \
  .orderBy(F.desc("number_of_tracks"), F.desc("avg_popularity"))
genre_statistics.show()

artists_by_genre = genre_artist_df.groupBy("artist_name","genre") \
  .agg(F.count("track_name").alias("number_of_tracks"),
       F.round(F.avg("popularity"), 3).alias("avg_popularity"),
       F.round(F.avg("danceability"), 3).alias("avg_danceability"), \
       F.round(F.avg("duration_ms"), 3).alias("avg_length (ms)")) \
  .orderBy(F.desc("number_of_tracks"), F.desc("avg_popularity"))
artists_by_genre.show()


most_popular_signatures = key_df.groupBy("key", "mode") \
  .agg(F.count("track_name").alias("number_of_tracks"),
       F.round(F.avg("popularity"), 3).alias("avg_popularity"),
       F.round(F.avg("loudness"), 3).alias("avg_loudness"),
       F.round(F.avg("energy"), 3).alias("avg_energy")) \
  .orderBy("key", "mode")
most_popular_signatures.show()

"""## New Aggregations"""

reduced_df = df.select("artist_name", "time_signature", "track_name",
  "popularity", "energy", "tempo")

# Artist grouped by time signatures
artist_time_signatures = (reduced_df.groupBy("artist_name", "time_signature")
  .agg(F.count("track_name").alias("number_of_tracks"),
       F.round(F.avg("popularity"), 3).alias("avg_popularity"),
       F.round(F.avg("energy"), 3).alias("energy"),
       F.round(F.avg("tempo"), 3).alias("avg_bpm"))
  .orderBy(F.desc("avg_popularity")))
artist_time_signatures.show()

# Bucketization of energy
from pyspark.ml.feature import Bucketizer
splits = [-float("inf"), .33, .66, float("inf")] # Split into 3 buckets low medium high [0,.33) [.33,.66) [.66,1]
bucketizer = Bucketizer(splits=splits, inputCol="energy", outputCol="energy_buckets")

energy_buckets = (bucketizer.transform(artist_time_signatures)
  .select("artist_name","time_signature","avg_popularity","energy_buckets")
  .withColumn("energy_buckets",
      F.when(F.col("energy_buckets")==0, "low")
      .when(F.col("energy_buckets")==1, "medium")
      .when(F.col("energy_buckets")==2, "high")))

popular_energy_counts = (energy_buckets.filter(F.col("avg_popularity").between(50, 100))
  .groupBy("energy_buckets")
  .agg(F.count("energy_buckets").alias("count")))
# We can see that the majority of the songs are rarer in their time signature
# from a particular artist and fit in our medium to high energy buckets
energy_buckets.show()
popular_energy_counts.show()

