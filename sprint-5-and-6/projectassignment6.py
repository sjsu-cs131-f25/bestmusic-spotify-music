# ML Model:
from pyspark.sql import functions as F
from pyspark.ml.feature import Bucketizer
from pyspark.ml.feature import VectorAssembler
from pyspark.ml.stat import Correlation

numeric_cols = [
    "acousticness", "danceability", "duration_ms", "energy",
    "instrumentalness", "liveness", "loudness",
    "speechiness", "tempo", "popularity", "valence"
]
for c in numeric_cols:
    df = df.withColumn(c, F.col(c).cast("float"))

q1, q2 = df.approxQuantile("popularity", [1/3, 2/3], 0.01) # Get quntiles .33 and .66
splits = [-float("inf"), q1, q2, float("inf")] # Split into 3 buckets low medium high [0,.33) [.33,.66) [.66,1]
bucketizer = Bucketizer(splits=splits, inputCol="popularity", outputCol="popularity_class")
df_labeled = bucketizer.transform(df).withColumn("label", F.col("popularity_class").cast("int")).drop("popularity_class")
# Add the popularity classification to the df
df_labeled.printSchema()

stats = df_labeled.select(
    [F.mean(c).alias(f"{c}_mean") for c in numeric_cols] +
    [F.stddev(c).alias(f"{c}_std") for c in numeric_cols] +
    [(F.max(c) - F.min(c)).alias(f"{c}_range") for c in numeric_cols]
    )

stats.show(truncate=False)
# Create 3 serperate dataframes and add them together
# From this we can see there is no issues with ranges, means or stds for any of the numeric columns

assembler = VectorAssembler(inputCols=numeric_cols, outputCol="corr_features")
df_corr = assembler.transform(df_labeled).select("corr_features")
corr_matrix = Correlation.corr(df_corr, "corr_features", "pearson").head()[0]
print(corr_matrix.toArray())
# Compute the correlation matrix between all numeric columns
# Essentially every value shows a correlation between two vectors
# Each vector is a numeric column
# If two correleations are close to 1, we remove one of the columns since it would be redundant
# All of the 1's form a diagonal, therefore there are no significant correlations
# All of the 1's come from a vector being compared to itself.

from pyspark.ml.feature import VectorAssembler, StandardScaler
from pyspark.ml.classification import RandomForestClassifier, LogisticRegression
from pyspark.ml.evaluation import MulticlassClassificationEvaluator

features = [c for c in numeric_cols if c != "popularity"]

assembler = VectorAssembler(
    inputCols=features,
    outputCol="features",
    handleInvalid="skip"
)

df_vec = assembler.transform(df_labeled).select("features", "label")

train, test = df_vec.randomSplit([0.8, 0.2], seed=42)

lr = LogisticRegression(
    labelCol="label",
    featuresCol="features",
    family="multinomial",
    maxIter=200,
    regParam=0.01,
    elasticNetParam=0.5
)

lr_model = lr.fit(train)
lr_pred  = lr_model.transform(test)

lr_model.write().overwrite().save(f"gs://{bucket}/out/mlmodel")
# lr_pred.write().overwrite().save(f"gs://{bucket}/output/mlpred")

evaluator = MulticlassClassificationEvaluator(
    labelCol="label", predictionCol="prediction", metricName="accuracy"
)

print("Accuracy:", evaluator.evaluate(lr_pred))